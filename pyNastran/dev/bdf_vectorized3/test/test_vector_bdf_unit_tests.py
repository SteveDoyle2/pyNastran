def _normalize_options(options: list[str]) -> set[str]:
    """Normalize case control options for comparison.

    Strips default options (SORT1, REAL) that the BDF parser adds
    explicitly but the H5 path correctly omits.
    """
    defaults = {'SORT1', 'REAL'}
    return {o.upper() for o in options} - defaults


def _compare_case_control(
    test_case: unittest.TestCase,
    bdf_cc,
    h5_cc,
    filename: str,
    skip_keys: set[str] | None = None,
) -> None:
    """Compare BDF and H5 case control decks, subcase by subcase.

    Parameters
    ----------
    test_case : unittest.TestCase
        The test instance (for assertions).
    bdf_cc : CaseControlDeck
        Case control from the BDF text path.
    h5_cc : CaseControlDeck
        Case control from the H5 path.
    filename : str
        Model name for error messages.
    skip_keys : set of str, optional
        Parameter names to skip. Defaults to known benign
        differences: ECHO (BDF-only directive), LABEL/TITLE
        (auto-generated in H5), NLSTRESS (auto-enabled by Nastran),
        and solution-dependent mappings (IC/TIC, TSTEPNL/TSTEP,
        ENTHALPY, THERMAL, FLUX for thermal models).
    """
    if skip_keys is None:
        skip_keys = {
            'ECHO',       # BDF directive, not stored in H5
            'LABEL',      # auto-generated by Nastran in H5
            # thermal/nonlinear solution-dependent name differences
            'ENTHALPY', 'THERMAL', 'FLUX',
            'IC', 'TIC',
            'TSTEPNL', 'TSTEP',
        }

    # Keys Nastran may auto-add in the H5 that aren't in the BDF
    h5_auto_keys = {
        'NLSTRESS',       # auto-enabled by Nastran
        'DISPLACEMENT',   # auto-enabled for thermal transient
        'VELOCITY',       # auto-enabled for thermal transient
    }

    all_sids = sorted(set(list(bdf_cc.subcases.keys()) +
                          list(h5_cc.subcases.keys())))
    for sid in all_sids:
        bdf_params = (bdf_cc.subcases[sid].params
                      if sid in bdf_cc.subcases else {})
        h5_params = (h5_cc.subcases[sid].params
                     if sid in h5_cc.subcases else {})

        bdf_keys = set(bdf_params.keys()) - skip_keys
        h5_keys = set(h5_params.keys()) - skip_keys
        common = bdf_keys & h5_keys

        # keys present in BDF but missing from H5
        bdf_only = bdf_keys - h5_keys
        # TITLE may live on subcase 0 in H5 vs per-subcase in BDF
        if 'TITLE' in bdf_only and sid != 0:
            bdf_only.discard('TITLE')
        test_case.assertEqual(
            bdf_only, set(),
            f'{filename} subcase {sid}: BDF-only keys {sorted(bdf_only)}')

        # keys present in H5 but missing from BDF
        h5_only = h5_keys - bdf_keys - h5_auto_keys
        if 'TITLE' in h5_only and sid == 0:
            h5_only.discard('TITLE')
        test_case.assertEqual(
            h5_only, set(),
            f'{filename} subcase {sid}: H5-only keys {sorted(h5_only)}')

        # compare values for common keys
        for key in sorted(common):
            bdf_val = bdf_params[key]
            h5_val = h5_params[key]

            # ECHO and other string-type params stored as raw strings
            if isinstance(bdf_val, str) or isinstance(h5_val, str):
                continue

            bdf_value = str(bdf_val[0]).upper()
            h5_value = str(h5_val[0]).upper()
            test_case.assertEqual(
                bdf_value, h5_value,
                f'{filename} subcase {sid} {key}: '
                f'value bdf={bdf_value} h5={h5_value}')

            bdf_opts = _normalize_options(bdf_val[1])
            h5_opts = _normalize_options(h5_val[1])
            # PRINT is the Nastran default medium; H5 stores it explicitly
            # while BDF parser may leave options empty
            if not bdf_opts and h5_opts == {'PRINT'}:
                continue
            test_case.assertEqual(
                bdf_opts, h5_opts,
                f'{filename} subcase {sid} {key}: '
                f'options bdf={sorted(bdf_opts)} h5={sorted(h5_opts)}')


class TestBdfVectorizedH5(unittest.TestCase):
    def test_h5(self):
        dirname = MODEL_PATH / 'elements'
        h5_filenames = [
            dirname / 'freq_elements.h5',
            dirname / 'freq_elements2.h5',
            dirname / 'time_thermal_elements.h5',
            dirname / 'static_elements.h5',
            dirname / 'modes_elements.h5',
            dirname / 'time_elements.h5',
            dirname / 'modes_complex_elements.h5',
            dirname / 'time_thermal_elements.h5',
            dirname / 'static_elements.h5',
            dirname / 'modes_elements.h5',
            dirname / 'time_elements.h5',
            dirname / 'modes_complex_elements.h5',
            dirname / 'freq_elements.h5',
            dirname / 'freq_elements2.h5',
            #dirname / 'loadstep_elements.h5',  # no nonlinear examples
        ]
        #log = SimpleLogger(level='warning')
        log = SimpleLogger(level='debug')
        for h5_filename in h5_filenames:
            log.warning(str(h5_filename))
            model = BDFv(log=log)
            model.read_h5(h5_filename)
            #break

    def test_h5_case_control(self):
        """Compare case control decks loaded from .bdf vs .h5 files.

        Tests that the H5 CASECC decoder produces the same case control
        parameters as the BDF text parser, for all element model variants.
        Tolerates known benign differences (ECHO, LABEL, NLSTRESS,
        thermal/nonlinear naming, default SORT1/REAL options).
        """
        dirname = MODEL_PATH / 'elements'
        bdf_h5_pairs = [
            ('freq_elements.bdf', 'freq_elements.h5'),
            ('freq_elements2.bdf', 'freq_elements2.h5'),
            ('static_elements.bdf', 'static_elements.h5'),
            ('time_thermal_elements.bdf', 'time_thermal_elements.h5'),
            ('modes_elements.bdf', 'modes_elements.h5'),
            ('time_elements.bdf', 'time_elements.h5'),
            ('modes_complex_elements.bdf', 'modes_complex_elements.h5'),
        ]
        log = SimpleLogger(level='error')
        for bdf_name, h5_name in bdf_h5_pairs:
            bdf_path = dirname / bdf_name
            h5_path = dirname / h5_name
            if not h5_path.exists():
                continue

            bdf_model = read_bdf_vectorized(bdf_path, log=log, xref=False)
            h5_model = BDFv(log=log)
            h5_model.read_h5(h5_path)

            self.assertIsNotNone(
                bdf_model.case_control_deck,
                f'{bdf_name}: BDF case control deck is None')
            self.assertIsNotNone(
                h5_model.case_control_deck,
                f'{h5_name}: H5 case control deck is None')

            _compare_case_control(
                self,
                bdf_model.case_control_deck,
                h5_model.case_control_deck,
                bdf_name,
            )


class TestBdfVectorized3(unittest.TestCase):
    @unittest.skipIf(not IS_PYTABLES, 'no hdf5')
    def test_static_solid_shell_bar_h5(self):
        log = SimpleLogger(level='warning')
        bdf_filename = MODEL_PATH / 'sol_101_elements' / 'static_solid_shell_bar.bdf'
        h5_filename = MODEL_PATH / 'sol_101_elements' / 'model_static_solid_shell_bar.h5'
        modelv = read_bdf_vectorized(bdf_filename, validate=True, xref=True, punch=False, log=log)
        modelv.write_h5(h5_filename)
        modelv2 = BDFv(log=log)
        modelv2.read_h5(h5_filename)

    def test_bwb(self):
        bdf_filename = MODEL_PATH / 'bwb' / 'bwb_saero.bdf'
        bdf_filename_out = MODEL_PATH / 'bwb' / 'bwb_saero_vectorized.bdf'
        modelv = read_bdf_vectorized(
            bdf_filename, validate=True, xref=True, punch=False,
            save_file_structure=False, skip_cards=None, read_cards=None,
            encoding=None, log=None, debug=False, mode='msc')
        model = read_bdf(
            bdf_filename, validate=True, xref=True, punch=False,
            save_file_structure=False, skip_cards=None, read_cards=None,
            encoding=None, log=None, debug=None, mode='msc')
        h5_filename = MODEL_PATH / 'bwb' / 'bwb_saero.h5'
        modelv.write_h5(h5_filename)
        model.write_h5(h5_filename)
        modelv2 = read_bdf_vectorized(h5_filename)
        os.remove(h5_filename)

        area, mass = get_compare_model_vectorized(model, modelv)
        modelv.cquad4.mass_breakdown()

        area_ctria3 = modelv.ctria3.area().sum()
        area_cquad4 = modelv.cquad4.area().sum()

        assert np.allclose(area['CTRIA3'], 7842.639526013481), area['CTRIA3']
        assert np.allclose(area['CQUAD4'], 2248660.627265879), area['CQUAD4']

        assert np.allclose(mass['CTRIA3'], 318.61913895889063), mass['CTRIA3']
        assert np.allclose(mass['CQUAD4'], 98307.632265389750), mass['CQUAD4']

        assert np.allclose(area_ctria3, 7842.639526013481), area_ctria3
        assert np.allclose(area_cquad4, 2248660.627265879), area_cquad4

        mass_ctria3 = modelv.ctria3.mass().sum()
        mass_cquad4 = modelv.cquad4.mass().sum()
        assert np.allclose(mass_ctria3, 318.61913895889063), mass_ctria3
        assert np.allclose(mass_cquad4, 98307.632265389750), mass_cquad4
        modelv.write_bdf(bdf_filename_out, size=16)
        modelv.write_bdf(bdf_filename_out)

def get_compare_model_vectorized(model, modelv):
    area = defaultdict(list)
    mass = defaultdict(list)
    for eid, elem in model.elements.items():
        etype = elem.type
        if etype in {'CTRIA3', 'CQUAD4'}:
            area[etype] += elem.Area()
            mass[etype] += elem.Mass()
        else:
            continue
            #asdf
    return area, mass

